const TABLES = { zh };

/** 当前语言(产品语言 zh-CN;未来可由设置键驱动) */
export const currentLang = 'zh';

/**
 * 取文案(纯函数):key=中文源文案,params={占位名:值} 做 {name} 插值;
 * 表未命中原样返回 key(未迁移文案零破坏)。
 */
export function t(key, params = null) {
  const table = TABLES[currentLang] || {};
  let text = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
